BATCHES = [(1, 45), (46, 85)]
CARET_RE = re.compile(r"\^(?:n|d\d+)")


def main() -> int:
    rows: dict[int, dict] = {}
    with (PROJECT / "catalog" / "scenario_catalog.jsonl").open(encoding="utf-8") as handle:
        for line in handle:
            item = json.loads(line)
            if item.get("file") == "1128.gsc" and item.get("slot") in TARGETS:
                rows[int(item["slot"])] = item
    if set(rows) != set(TARGETS):
        raise SystemExit("catalog mismatch")

    results = []
    for start, end in BATCHES:
        entries = []
        for index in range(start, end + 1):
            source = str(rows[index]["source_text"])
            target = TARGETS[index]
            if CARET_RE.findall(source) != CARET_RE.findall(target):
                raise SystemExit(f"caret mismatch {index}")
            target.encode("cp949", errors="strict")
            entries.append({
                "uid": rows[index]["uid"],
                "source_text": source,
                "source_raw_sha256": rows[index]["source_raw_sha256"],
                "target_text": target,
                "translator": "Codex internal model draft",
                "review_status": "draft_pending_single_review",
                "notes": "초벌 번역; 1차 검수 전",
            })
        scope = f"1128_slots_{start:05d}_{end:05d}_draft"
        output = {
            "schema": "fairytale-requiem-translation-map-v1",
            "scope": scope,
            "semantic_source": "ja-JP",
            "target_language": "ko-KR",
            "target_encoding": "cp949",
            "translation_method": "Codex internal model only; no external MT/API",
            "review_passes_completed": 0,
            "release_ready": False,
            "entries": entries,
        }
        out = PROJECT / "packets" / "drafts" / f"{scope}.json"
        out.write_text(json.dumps(output, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        results.append({
            "output": str(out),
            "entries": len(entries),
            "sha256": hashlib.sha256(out.read_bytes()).hexdigest().upper(),
        })
    print(json.dumps({"status": "PASS", "outputs": results}, ensure_ascii=True, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
