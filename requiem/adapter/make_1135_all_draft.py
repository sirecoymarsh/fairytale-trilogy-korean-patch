def parse_targets() -> dict[int, str]:
    targets: dict[int, str] = {}
    for line in RAW_TARGETS.strip().splitlines():
        slot_text, target = line.split("\t", 1)
        slot = int(slot_text)
        if slot in targets:
            raise SystemExit(f"duplicate slot: {slot}")
        targets[slot] = target
    expected = set(range(1, 299))
    if set(targets) != expected:
        raise SystemExit(
            f"target coverage mismatch: missing={sorted(expected-set(targets))}, "
            f"extra={sorted(set(targets)-expected)}"
        )
    return targets


